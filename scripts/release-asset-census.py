#!/usr/bin/env python3
"""Generate a dated GitHub Release ISO census for the adoption snapshot (#3149).

Counters cover the lifetime of retained assets, not a calendar-month interval.
R2 objects, external contributors and installs are outside this census.
"""

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
DESKTOPS = ("gnome", "kde", "xfce", "cosmic", "niri")
REPO = "tuna-os/tunaos"


def gh_json(endpoint, paginate=False):
    command = ["gh", "api", endpoint]
    if paginate:
        command += ["--paginate", "--slurp"]
    # Inherit GH_TOKEN. A failed page must never become a zero in the report.
    result = subprocess.run(command, check=True, text=True, capture_output=True)
    value = json.loads(result.stdout)
    return [item for page in value for item in page] if paginate else value


def summarize(releases, config):
    variants = {variant["id"]: variant for variant in config["variants"]}
    cells = {
        (name, desktop): {"assets": 0, "lifetime_downloads": 0,
                          "iso_enabled": any(f["id"] == desktop and f.get("build_iso", False)
                                             for f in variant["flavors"])}
        for name, variant in variants.items() for desktop in DESKTOPS
    }
    iso_assets = []
    non_iso_downloads = 0
    non_iso_assets = 0
    release_count = 0
    seen = set()
    for release in releases:
        if release["draft"] or release["prerelease"]:
            continue
        release_count += 1
        for asset in release["assets"]:
            if asset["id"] in seen:
                raise ValueError(f"Duplicate asset ID: {asset['id']}")
            seen.add(asset["id"])
            count = asset["download_count"]
            if type(count) is not int or count < 0:
                raise ValueError("Invalid download counter")
            if not asset["name"].lower().endswith(".iso"):
                non_iso_assets += 1
                non_iso_downloads += count
                continue
            name = asset["name"].lower()
            variant = next((v for v in sorted(variants, key=len, reverse=True)
                            if name.startswith(v + "-")), None)
            suffix = name[len(variant) + 1:] if variant else ""
            desktop = next((d for d in DESKTOPS if suffix.startswith(d + "-")), None)
            cell = (variant, desktop)
            if cell in cells:
                cells[cell]["assets"] += 1
                cells[cell]["lifetime_downloads"] += count
            iso_assets.append({
                "id": asset["id"], "name": asset["name"],
                "url": asset["browser_download_url"], "tag": release["tag_name"],
                "created_at": asset["created_at"], "updated_at": asset["updated_at"],
                "lifetime_downloads": count, "variant": variant, "desktop": desktop,
            })
    return {
        "public_non_prerelease_releases": release_count,
        "non_iso_assets": non_iso_assets, "non_iso_lifetime_downloads": non_iso_downloads,
        "iso_assets": sorted(iso_assets, key=lambda a: a["id"]),
        "cells": [{"variant": v, "desktop": d, **values}
                  for (v, d), values in sorted(cells.items())],
    }


def render(receipt):
    data = receipt["data"]
    assets = data["iso_assets"]
    lines = [
        "<!-- Generated by scripts/release-asset-census.py; do not edit. -->",
        "# GitHub Release ISO census", "",
        f"**Collection started (UTC):** {receipt['started_at']}",
        f"**Collection ended (UTC):** {receipt['finished_at']}",
        f"**Source commit:** `{receipt['source_commit']}`", "",
        "This is a dated inventory of retained public releases. Counters cover",
        "each asset's lifetime. They do not measure October downloads or installs.",
        "R2 downloads and removed assets are outside this inventory.", "",
        "| Measure | Count |", "|---|---:|",
        f"| Stars at collection | {receipt['repository']['stargazers_count']} |",
        f"| Forks at collection | {receipt['repository']['forks_count']} |",
        f"| Public releases, with prereleases excluded | {data['public_non_prerelease_releases']} |",
        f"| Retained ISO assets | {len(assets)} |",
        f"| ISO downloads, lifetime | {sum(a['lifetime_downloads'] for a in assets)} |",
        f"| Other assets | {data['non_iso_assets']} |",
        f"| Other downloads, lifetime (cards, SBOMs, etc.) | {data['non_iso_lifetime_downloads']} |",
        "", "## ISO presence by variant and desktop", "",
        "Cells show the number of retained ISO assets. `0` means no ISO asset",
        "in these GitHub releases. `n/a` means the base desktop has no ISO build",
        "in the source config. These values do not describe availability on R2 or boot quality.",
        "Overlay flavors roll up to their desktop. A combined ISO without a",
        "desktop in its name stays outside this matrix.", "",
        "| Variant | GNOME | KDE | XFCE | COSMIC | Niri |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    cells = {(c["variant"], c["desktop"]): c for c in data["cells"]}
    for variant in sorted({c["variant"] for c in data["cells"]}):
        values = [cells[variant, d] for d in DESKTOPS]
        lines.append(f"| {variant} | " + " | ".join(
            str(c["assets"]) if c["assets"] or c["iso_enabled"] else "n/a"
            for c in values) + " |")
    lines += ["", "## Top ten variant and desktop pairs", ""]
    ranked = sorted((c for c in data["cells"] if c["lifetime_downloads"] > 0),
                    key=lambda c: (-c["lifetime_downloads"], c["variant"], c["desktop"]))[:10]
    if ranked:
        lines += ["Lifetime ISO counters only; monthly performance remains unmeasured.", "",
                  "| Variant | Desktop | Lifetime ISO downloads |", "|---|---|---:|"]
        lines += [f"| {c['variant']} | {c['desktop']} | {c['lifetime_downloads']} |" for c in ranked]
    else:
        lines += ["No pair has a positive ISO counter. There is no measured rank."]
    unattributed = [a for a in assets if not a["variant"] or not a["desktop"]]
    lines += ["", f"ISO assets outside the matrix: {len(unattributed)}.", "",
              "## Asset evidence", "", "| Asset ID | ISO | Lifetime downloads |",
              "|---|---|---:|"]
    lines += [f"| {a['id']} | [{a['name']}]({a['url']}) | {a['lifetime_downloads']} |" for a in assets]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True, help="new receipt path, without a suffix")
    args = parser.parse_args()
    targets = [args.output.with_suffix(suffix) for suffix in (".json", ".md")]
    if any(path.exists() for path in targets):
        parser.error("use a new path to preserve the previous receipt")
    from lib import tunaos_config
    config = json.loads(tunaos_config.render(tunaos_config.load(ROOT / "tunaos.toml")))
    receipt = {"schema": 1, "started_at": datetime.now(timezone.utc).isoformat(),
               "source_commit": subprocess.check_output(
                   ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
               "config_sha256": hashlib.sha256((ROOT / "tunaos.toml").read_bytes()).hexdigest(),
               "endpoints": [f"repos/{REPO}", f"repos/{REPO}/releases?per_page=100"]}
    repo = gh_json(receipt["endpoints"][0])
    receipt["repository"] = {key: repo[key] for key in ("html_url", "stargazers_count", "forks_count")}
    releases = gh_json(receipt["endpoints"][1], paginate=True)
    for release in releases:
        # Fetch a separate asset listing if the embedded list could be a full page.
        if len(release["assets"]) >= 30:
            endpoint = f"repos/{REPO}/releases/{release['id']}/assets?per_page=100"
            receipt["endpoints"].append(endpoint)
            release["assets"] = gh_json(endpoint, paginate=True)
    receipt["data"] = summarize(releases, config)
    receipt["finished_at"] = datetime.now(timezone.utc).isoformat()
    markdown = render(receipt)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    targets[0].write_text(json.dumps(receipt, indent=2) + "\n")
    targets[1].write_text(markdown)


if __name__ == "__main__":
    main()
