#!/usr/bin/env python3
"""Generate the #3152 issue index; workflow measurements stay in the #2916 audit.

Refresh uses read-only GitHub search API calls. Rendering uses the committed
snapshot, so reviewers can reproduce the index without network access.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import html
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
QUERIES = (
    'org:tuna-os is:issue is:open in:title permissions',
    'org:tuna-os is:issue is:open in:title unpinned',
    'org:tuna-os is:issue is:open in:title pin action',
)


def collect_issues(queries=QUERIES, run=subprocess.run):
    """Deduplicate search pages, failing on GitHub's partial/1000-result limit."""
    issues = {}
    for query in queries:
        result = run(
            ['gh', 'api', '--method', 'GET', 'search/issues',
             '-f', f'q={query}', '-f', 'per_page=100', '--paginate', '--slurp'],
            check=True, capture_output=True, text=True,
        )
        pages = json.loads(result.stdout)
        if not pages or any(page['incomplete_results'] for page in pages):
            raise ValueError(f'Incomplete GitHub search: {query}')
        items = [item for page in pages for item in page['items']]
        if len(items) != pages[0]['total_count'] or len(items) > 1000:
            raise ValueError(f'Truncated GitHub search: {query}')
        for item in items:
            repo = item['repository_url'].removeprefix('https://api.github.com/repos/')
            if not re.fullmatch(r'tuna-os/[A-Za-z0-9_.-]+', repo):
                raise ValueError(f'Unexpected repository: {repo}')
            if 'pull_request' in item or item['state'] != 'open':
                raise ValueError(f'Unexpected search result: {item["html_url"]}')
            issues[item['html_url']] = {
                'repository': repo, 'number': item['number'],
                'title': item['title'], 'url': item['html_url'],
                'updated_at': item['updated_at'],
            }
    return {
        'generated_at': datetime.now(timezone.utc).isoformat(timespec='seconds'),
        'queries': list(queries),
        'issues': sorted(issues.values(), key=lambda i: (i['repository'].lower(), i['number'])),
    }


def render(snapshot):
    groups = {}
    for issue in snapshot['issues']:
        groups.setdefault(issue['repository'], []).append(issue)
    lines = [
        '# Workflow security issue index', '',
        '<!-- Generated by scripts/gen-workflow-security-rollout.py; do not edit. -->', '',
        f'Snapshot: {snapshot["generated_at"]}.', '',
        f'{len(snapshot["issues"])} open issues in {len(groups)} repositories match the title queries below.',
        'These are issue counts, not counts of affected workflows or confirmed vulnerabilities.',
        'Duplicates remain visible under each repository. Search does not inspect workflow contents,',
        'and findings without these title terms are outside this index.', '',
        'Use the [rollout runbook](WORKFLOW-SECURITY-ROLLOUT.md) to validate each report',
        'and link each consumer PR to the issues it covers. Do not close findings from this index alone.', '',
        '## Search scope', '', '```text', *snapshot['queries'], '```', '',
        '## Findings by repository', '',
    ]
    for repo, issues in sorted(groups.items(), key=lambda pair: pair[0].lower()):
        lines += [f'### {repo}', '', '| Issue | Report |', '| --- | --- |']
        for issue in sorted(issues, key=lambda i: i['number']):
            title = html.escape(issue['title']).replace('[', '&#91;').replace(']', '&#93;')
            title = title.replace('|', '&#124;').replace('\n', ' ').replace('*', '&#42;').replace('_', '&#95;').replace('`', '&#96;')
            lines.append(f'| [#{issue["number"]}]({issue["url"]}) | {title} |')
        lines.append('')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--refresh', action='store_true', help='Read GitHub and replace the snapshot')
    parser.add_argument('--check', action='store_true', help='Check that the index matches the snapshot')
    parser.add_argument('--snapshot', type=Path, default=ROOT / 'docs/data/workflow-security-issues.json')
    parser.add_argument('--output', type=Path, default=ROOT / 'docs/WORKFLOW-SECURITY-ROLLOUT-INDEX.md')
    args = parser.parse_args()
    if args.refresh and args.check:
        parser.error('--refresh and --check cannot be combined')
    try:
        if args.refresh:
            snapshot = collect_issues()
            args.snapshot.parent.mkdir(parents=True, exist_ok=True)
            args.snapshot.write_text(json.dumps(snapshot, indent=2) + '\n')
        else:
            snapshot = json.loads(args.snapshot.read_text())
        output = render(snapshot)
        if args.check:
            if args.output.read_text() != output:
                print('Workflow security index differs from the snapshot; regenerate it.')
                return 1
        else:
            args.output.write_text(output)
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as exc:
        parser.exit(2, f'Workflow security index failed: {exc}\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
