#!/usr/bin/env python3
"""Write installer-medium/docs/cells.md from the medium resolver (tunaOS#4905).

Usage: scripts/gen-installer-medium-cells.py [--check]

The table is derived, never typed: every row comes from
scripts/lib/installer_medium.py over tunaos.toml and the evidence files in
installer-medium/evidence/. `--check` fails when the checked-in file is stale;
tests/test_installer_medium_docs.py runs it.
"""

import argparse
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "installer-medium/docs/cells.md"


def load():
    spec = importlib.util.spec_from_file_location("c", ROOT / "scripts/lib/tunaos_config.py")
    config = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(config)
    return config.load(ROOT / "tunaos.toml"), config.installer_medium_policy()


def evidence_cell(row):
    if row["status"] in ("promoted", "supported"):
        if row["source"] == "declared":
            return f"declared: {row['reason']}"
        return f"`{row['digest'][7:19]}` read {row['read']}"
    return row["reason"]


def render(primary, medium):
    rows = medium.resolve(primary)
    count = {status: sum(1 for row in rows if row["status"] == status) for status in medium.STATUSES}
    lines = [
        "# Installer medium cells",
        "",
        "<!-- Generated by scripts/gen-installer-medium-cells.py. Do not edit. -->",
        "",
        "One row per variant:flavor of the `tunaos.toml` matrix that has a desktop,",
        "plus the declared sibling cell. `scripts/lib/installer_medium.py` resolves",
        "each row. The digest is the image the probe inputs came from",
        "(`installer-medium/evidence/images.json`).",
        "",
        f"- Promoted (nightly): {count['promoted']}",
        f"- Supported, not promoted (dispatch by cell name): {count['supported']}",
        f"- Unverified (no medium until the reason is fixed): {count['unverified']}",
        f"- No medium (headless flavors): {count['no-medium']}",
        "",
        "| Cell | Frontend | Installer | Filesystem | Bootloader | Backend | Arch | Status | Evidence or reason |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        if row["status"] == "no-medium":
            continue
        lines.append(
            "| `{cell}` | {frontend} | {installer} | {fs} | {bl} | {be} | {arch} | {status} | {why} |".format(
                cell=row["cell"],
                frontend=row["frontend"],
                installer=row["installer"],
                fs=row["filesystem"] or "-",
                bl=row["bootloader"] or "-",
                be=row["backend"] or "-",
                arch=", ".join(row["architectures"]),
                status=row["status"],
                why=evidence_cell(row),
            )
        )
    headless = [row["cell"] for row in rows if row["status"] == "no-medium"]
    lines += [
        "",
        "## Flavors with no medium",
        "",
        "A headless flavor has no graphical session, so it gets no medium:",
        ", ".join(f"`{cell}`" for cell in headless) + ".",
        "",
        "## Bootloader target (tunaOS#4955)",
        "",
        "The Bootloader column above is what each image carries today, and a",
        "medium built today must use it. This table is the separate target:",
        "systemd-boot where the base publishes a signed systemd-boot that its shim",
        "accepts. No cell switches bootloader from this table.",
        "",
        "| Variant | Base | Today | Signed systemd-boot | Signer | bootc `--bootloader systemd` | Target | Reason |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for target in medium.bootloader_targets(primary):
        lines.append(
            "| `{variant}` | {base} | {today} | {signed} | {signer} | {bootc} | {target} | {reason} |".format(
                variant=target["variant"],
                base=target["base"] or "-",
                today=target["today"] or "-",
                signed=target["signed"],
                signer=target["signer"] or "-",
                bootc=target["bootc_systemd"],
                target=target["target"],
                reason=target["reason"],
            )
        )
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render(*load())
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run scripts/gen-installer-medium-cells.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
