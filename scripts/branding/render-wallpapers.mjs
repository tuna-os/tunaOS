#!/usr/bin/env node
// Regenerates the per-variant wallpapers from the identity table.
//
//   node scripts/branding/render-wallpapers.mjs
//
// Needs Playwright with a Chromium (the render is a headless screenshot of an
// SVG). The outputs are committed, so builds never run this; rerun it after
// changing build_scripts/lib/variant-identity.tsv, a scene in
// wallpaper.svg.mjs or an emoji under scripts/branding/emoji/, and commit what
// it writes:
//
//   system_files/usr/share/backgrounds/tunaos/<id>.jpg   one per variant
//   system_files/usr/share/backgrounds/tunaos/tunaos-default.jpg   generic 🐟
//   system_files/usr/share/gnome-background-properties/tunaos.xml
//
// JPEG, not PNG: a 4K gradient is ~1.6 MB as PNG and ~150 KB as JPEG, and
// every image carries all fourteen so users can pick a sibling's.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
import { wallpaperSvg } from './wallpaper.svg.mjs';

const repo = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const require = createRequire(import.meta.url);
let chromium;
try {
  ({ chromium } = require('playwright'));
} catch {
  const globalRoot = execSync('npm root -g').toString().trim();
  ({ chromium } = createRequire(join(globalRoot, 'noop.js'))('playwright'));
}

const rows = readFileSync(join(repo, 'build_scripts/lib/variant-identity.tsv'), 'utf8')
  .split('\n')
  .filter((l) => l && !l.startsWith('#'))
  .map((l) => {
    const [id, accent, gnomeAccent, base, homage] = l.split('\t');
    return { id, accent, gnomeAccent, base, homage };
  });

const outDir = join(repo, 'system_files/usr/share/backgrounds/tunaos');
mkdirSync(outDir, { recursive: true });

const jobs = [
  ...rows.map((r) => ({ ...r, file: `${r.id}.jpg` })),
  // The generic TunaOS scene, for any image that has no variant of its own.
  { id: 'tunaos', accent: '#1E6FB0', file: 'tunaos-default.jpg' },
];

const executablePath = process.env.CHROMIUM_PATH || '/opt/pw-browsers/chromium';
const browser = await chromium.launch({ executablePath }).catch(() => chromium.launch());
const page = await browser.newPage({ viewport: { width: 3840, height: 2160 } });
for (const job of jobs) {
  const svg = wallpaperSvg({ id: job.id, accent: job.accent });
  await page.setContent(`<html><body style="margin:0">${svg}</body></html>`);
  await page.screenshot({ path: join(outDir, job.file), type: 'jpeg', quality: 90 });
  console.log(`wrote ${job.file}`);
}
await browser.close();

// GNOME Settings > Appearance lists wallpapers from this file, so every
// variant's wallpaper is one click away on every image.
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const entries = rows
  .map((r) => `  <wallpaper deleted="false">
    <name>${cap(r.id)}</name>
    <filename>/usr/share/backgrounds/tunaos/${r.id}.jpg</filename>
    <options>zoom</options>
    <shade_type>solid</shade_type>
    <pcolor>${r.accent}</pcolor>
    <scolor>#05070d</scolor>
  </wallpaper>`)
  .join('\n');
const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/branding/render-wallpapers.mjs; do not edit. -->
<!DOCTYPE wallpapers SYSTEM "gnome-wp-list.dtd">
<wallpapers>
${entries}
</wallpapers>
`;
const xmlDir = join(repo, 'system_files/usr/share/gnome-background-properties');
mkdirSync(xmlDir, { recursive: true });
writeFileSync(join(xmlDir, 'tunaos.xml'), xml);
console.log('wrote gnome-background-properties/tunaos.xml');
