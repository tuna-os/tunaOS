#!/usr/bin/env python3
"""Check explicit workflow token baselines locally or audit an organization (#2916)."""

import argparse
import base64
from concurrent.futures import ThreadPoolExecutor
import json
import os
from pathlib import Path
import subprocess
import sys
from urllib.parse import quote

import yaml


def findings(text):
    """Jobs may inherit an explicit baseline; explicit overrides must be maps."""
    try:
        workflow = yaml.safe_load(text)
    except yaml.YAMLError as error:
        return [f"invalid YAML: {error}"]
    if not isinstance(workflow, dict):
        return ["workflow must be a mapping"]
    errors = []
    if "permissions" not in workflow:
        errors.append("missing top-level permissions")
    elif not isinstance(workflow["permissions"], dict) and workflow["permissions"] != "read-all":
        errors.append("top-level permissions must be a map or read-all")
    jobs = workflow.get("jobs", {})
    if not isinstance(jobs, dict):
        return errors + ["jobs must be a mapping"]
    for name, job in jobs.items():
        if isinstance(job, dict) and "permissions" in job:
            if not isinstance(job["permissions"], dict) and job["permissions"] != "read-all":
                errors.append(f"job {name}: permissions must be a map or read-all")
    return errors


def api(endpoint):
    # Use the contributor's designated token, never gh's alternate environment token.
    env = dict(os.environ)
    if env.get("GH_TOKEN"):
        env["GITHUB_TOKEN"] = env["GH_TOKEN"]
    result = subprocess.run(
        ["gh", "api", endpoint], env=env, check=True, capture_output=True, text=True, timeout=60
    )
    return json.loads(result.stdout)


def audit_repository(repo):
    record = {"repository": repo["full_name"], "branch": repo["default_branch"],
              "archived": repo["archived"], "workflows": []}
    try:
        if repo["size"] == 0:
            record["empty"] = True
            return record
        root = f"repos/{repo['full_name']}/git"
        commit = api(f"repos/{repo['full_name']}/commits/{quote(repo['default_branch'], safe='')}")
        record["commit"] = commit["sha"]
        tree = api(f"{root}/trees/{commit['commit']['tree']['sha']}?recursive=1")
        if tree.get("truncated"):
            raise ValueError("truncated repository tree; audit incomplete")
        for item in tree["tree"]:
            path = Path(item["path"])
            if str(path.parent) != ".github/workflows" or path.suffix not in (".yml", ".yaml"):
                continue
            if item["mode"] != "100644" and item["mode"] != "100755":
                raise ValueError(f"unsupported workflow entry: {path}")
            blob = api(f"{root}/blobs/{item['sha']}")
            text = base64.b64decode(blob["content"]).decode("utf-8")
            record["workflows"].append({"path": str(path), "findings": findings(text)})
    except (subprocess.SubprocessError, OSError, ValueError, KeyError) as error:
        record["error"] = str(error)
    return record


def audit_org(org):
    repos = []
    page = 1
    while True:
        batch = api(f"orgs/{org}/repos?per_page=100&page={page}")
        repos.extend(batch)
        if len(batch) < 100:
            break
        page += 1
    with ThreadPoolExecutor(max_workers=6) as pool:
        return list(pool.map(audit_repository, sorted(repos, key=lambda repo: repo["full_name"])))


def markdown_report(records):
    lines = ["<!-- Generated by scripts/check-workflow-permissions.py --org tuna-os --markdown. -->",
             "# Organization workflow permission audit", "",
             "Default branches at the recorded commits; includes archived repositories.",
             "The check finds explicit baselines. Review each grant separately.", "",
             "| Repository | Commit | Workflows | Findings |",
             "|---|---|---:|---|"]
    for record in records:
        repo = record["repository"]
        sha = record.get("commit", "")
        commit = f"[{sha[:12]}](https://github.com/{repo}/commit/{sha})" if sha else "empty"
        issues = [f"`{w['path']}`: {', '.join(w['findings'])}"
                  for w in record["workflows"] if w["findings"]]
        if record.get("error"):
            issues.append(record["error"])
            if not sha:
                commit = "unavailable"
        details = "; ".join(issues).replace("|", "&#124;").replace("\n", " ") or "none"
        lines.append(f"| {repo} | {commit} | {len(record['workflows'])} | {details} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", nargs="?", type=Path, default=Path("."))
    parser.add_argument("--org", help="audit all visible repositories, including archived ones, using gh")
    parser.add_argument("--markdown", action="store_true", help="emit a generated audit table")
    args = parser.parse_args()
    if args.org:
        try:
            records = audit_org(args.org)
        except (subprocess.SubprocessError, OSError, ValueError) as error:
            parser.exit(2, f"Organization audit failed: {error}\n")
    else:
        directory = args.root / ".github/workflows"
        if not directory.is_dir():
            print(f"workflow directory not found: {directory}", file=sys.stderr)
            return 1
        workflows = []
        for path in sorted(directory.glob("*")):
            if path.suffix in (".yml", ".yaml"):
                workflows.append({"path": str(path.relative_to(args.root)),
                                  "findings": findings(path.read_text())})
        if not workflows:
            print(f"no workflow files found in {directory}", file=sys.stderr)
            return 1
        records = [{"repository": str(args.root), "workflows": workflows}]
    if not args.org:
        for workflow in records[0]["workflows"]:
            for finding in workflow["findings"]:
                print(f"{workflow['path']}: {finding}", file=sys.stderr)
    print(markdown_report(records) if args.markdown else json.dumps(records, indent=2))
    return int(any(record.get("error") or any(w["findings"] for w in record["workflows"])
                   for record in records))


if __name__ == "__main__":
    raise SystemExit(main())
